#!/usr/bin/env python3
# Writes a wx/wxscintilla.h that puts Code::Blocks' editor on the toolkit's
# wxStyledTextCtrl (the one Scintilla, in GFOpenWX) in place of the
# wxScintilla copy Code::Blocks carries. It reads Code::Blocks' own header
# for the names it uses: every wxSCI_ constant becomes the wxSTC_ one when
# the toolkit has it (its own value otherwise, for the few Code::Blocks
# added), and every wxEVT_SCI_ and EVT_SCI_ name the wxSTC_ one.
#   scicompat.py CB-wxscintilla.h OUT.h
# Copyright (c) 2026 AmiCradle Team
import re, sys

src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding='latin-1').read()

consts = []
for m in re.finditer(r'^#define\s+wxSCI_(\w+)\s+(.+?)\s*(?://.*)?$', text, re.M):
    consts.append((m.group(1), m.group(2)))
events = sorted(set(re.findall(r'\bwxEVT_SCI_(\w+)', text)))
macros = sorted(set(re.findall(r'^#define\s+EVT_SCI_(\w+)\(', text, re.M)))

o = []
w = o.append
w('// Generated by scicompat.py from Code::Blocks\' wxscintilla.h: the editor')
w('// on the toolkit\'s wxStyledTextCtrl. Do not edit.')
w('#ifndef CB_WXSCINTILLA_COMPAT_H')
w('#define CB_WXSCINTILLA_COMPAT_H')
w('#include <wx/stc/stc.h>')
w('')
for name, value in consts:
    w('#ifdef wxSTC_%s' % name)
    w('#define wxSCI_%s wxSTC_%s' % (name, name))
    w('#else')
    w('#define wxSCI_%s %s' % (name, re.sub(r'\bwxSCI_', 'wxSCI_', value)))
    w('#endif')
w('')
for e in events:
    w('#define wxEVT_SCI_%s wxEVT_STC_%s' % (e, e))
for e in macros:
    w('#define EVT_SCI_%s(id, fn) EVT_STC_%s(id, fn)' % (e, e))
w('''
typedef wxStyledTextEvent wxScintillaEvent;
typedef wxStyledTextEventFunction wxScintillaEventFunction;
#define wxScintillaEventHandler(func) wxStyledTextEventHandler(func)
#define wxSCINameStr wxASCII_STR(wxSTCNameStr)

// The few calls Code::Blocks added to its copy, on wxStyledTextCtrl's own
class WXDLLIMPEXP_STC wxScintilla : public wxStyledTextCtrl
{
public:
    wxScintilla() {}
    wxScintilla(wxWindow *parent, wxWindowID id = wxID_ANY,
                const wxPoint& pos = wxDefaultPosition,
                const wxSize& size = wxDefaultSize, long style = 0,
                const wxString& name = wxASCII_STR(wxSTCNameStr))
        : wxStyledTextCtrl(parent, id, pos, size, style, name) {}

    void SetSelectionVoid(int from, int to) { SetSelection(from, to); }
    void SetSelectionInt(int from, int to) { SetSelection(from, to); }
    void SetSCIFocus(bool focus) { SetSTCFocus(focus); }
    bool GetSCIFocus() const { return GetSTCFocus(); }
    void SetSCICursor(int cursorType) { SetSTCCursor(cursorType); }
    int GetSCICursor() const { return GetSTCCursor(); }
    bool HaveMouseCapture() { return HasCapture(); }
    void SetMouseCapture(bool on)
    {
        if (on && !HasCapture()) CaptureMouse();
        else if (!on && HasCapture()) ReleaseMouse();
    }
    // the change bar is Code::Blocks' own addition to Scintilla's core:
    // without it no line is marked changed
    void SetChangeCollection(bool) {}
    int FindChangedLine(const int, const int) const { return wxSTC_INVALID_POSITION; }
    using wxStyledTextCtrl::EmptyUndoBuffer;
    void EmptyUndoBuffer(bool) { wxStyledTextCtrl::EmptyUndoBuffer(); }

    wxDECLARE_DYNAMIC_CLASS(wxScintilla);
};
#endif''')
open(out, 'w').write('\n'.join(o) + '\n')
print('wxscintilla.h: %d constants, %d events on wxStyledTextCtrl' % (len(consts), len(events)))
